  /// Translates [key], replacing `{placeholder}` tokens from [args].
  String t(String key, [Map<String, String> args = const {}]) {
    var value = _strings[key] ??
        _extendedStrings[locale.languageCode]?[key] ??
        _fallback[key] ??
        _extendedStrings['en']?[key] ??
        key;
    args.forEach((k, v) => value = value.replaceAll('{$k}', v));
    return value;
  }

  static Map<String, String> _decode(String raw) =>
      (jsonDecode(raw) as Map<String, dynamic>)
          .map((k, v) => MapEntry(k, v.toString()));

  static Future<AppLocalizations> load(Locale locale, {AssetBundle? bundle}) {
    final fallback = _extendedStrings['en']!;
    if (bundle == null && _extendedStrings.containsKey(locale.languageCode)) {
      return SynchronousFuture<AppLocalizations>(
        AppLocalizations(
          locale,
          _extendedStrings[locale.languageCode]!,
          fallback,
        ),
      );
    }
    return _loadFromBundle(locale, bundle ?? rootBundle, fallback);
  }

  static Future<AppLocalizations> _loadFromBundle(
    Locale locale,
    AssetBundle b,
    Map<String, String> fallback,
  ) async {
    var strings = fallback;
    try {
      strings = _decode(
        await b.loadString('assets/locales/${locale.languageCode}.json'),
      );
    } catch (_) {
      strings = _extendedStrings[locale.languageCode] ?? fallback;
    }
    return AppLocalizations(locale, strings, fallback);
  }
}

class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      AppLocalizations.supportedCodes.contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) => AppLocalizations.load(locale);

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}
